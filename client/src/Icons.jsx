export function Avatar({ user, size = 28 }) {
  const n = user?.name || '?';
  let h = 0;
  for (const c of n) h = (h * 31 + c.charCodeAt(0)) % 360;
  return (
    <span className="avatar" title={n} style={{ width: size, height: size, fontSize: size * 0.42, background: `hsl(${h} 45% 40%)` }}>
      {n.trim()[0]?.toUpperCase()}
    </span>
  );
}
